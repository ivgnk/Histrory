# Эта функция полезна, когда вы хотите получить детальную информацию
# о конкретном режиме: время максимума, равновесную массу, периоды и т.д.
# =============================================================================
def analyze_equilibrium(lambda1, lambda2, N0=100):
    """
    Анализ времени установления равновесия и массы N₂ в равновесии.
    Выводит подробную текстовую информацию о режиме работы системы.
    """

    T1 = np.log(2) / lambda1 if lambda1 > 0 else np.inf
    T2 = np.log(2) / lambda2 if lambda2 > 0 else np.inf

    print("=" * 60)
    print("АНАЛИЗ ЦЕПОЧКИ РАДИОАКТИВНОГО РАСПАДА")
    print("=" * 60)
    print(f"λ₁ = {lambda1:.4e}, T₁ = {T1:.4f}")
    print(f"λ₂ = {lambda2:.4e}, T₂ = {T2:.4f}")
    print(f"Отношение λ₁/λ₂ = {lambda1 / lambda2:.4f}")
    print("-" * 60)

    # Определяем режим
    if abs(lambda1 - lambda2) < 1e-12:
        print("РЕЖИМ: ВЫРОЖДЕННЫЙ (λ₁ = λ₂)")
        t_max_N2 = 1 / lambda1
        N2_max = N0 * lambda1 * t_max_N2 * np.exp(-1)
        print(f"Максимум N₂: t = {t_max_N2:.4f}, масса = {N2_max / N0:.2%} от N₀")
        print("Формула: N₂(t) = N₀·λ·t·e^(-λt)")

    elif lambda1 < lambda2:
        # Вековое равновесие (материнский распад медленнее дочернего)
        N2_eq = N0 * lambda1 / lambda2
        t_eq = 5 * T2  # Время установления равновесия (~5 периодов дочернего)
        print("РЕЖИМ: ВЕКОВОЕ РАВНОВЕСИЕ (λ₁ < λ₂)")
        print(f"Масса N₂ в равновесии: {N2_eq:.2f}% от N₀")
        print(f"Время установления равновесия: t ≈ {t_eq:.2f} (≈ 5·T₂)")
        print("Активность N₂ ≈ активности N₁: λ₂·N₂ ≈ λ₁·N₁")
        # Время достижения максимума (до установления равновесия)
        t_max = np.log(lambda1 / lambda2) / (lambda1 - lambda2)
        if t_max > 0:
            print(f"Время достижения максимума N₂: t = {t_max:.4f}")

    else:  # lambda1 > lambda2
        # Переходный режим (материнский распад быстрее дочернего)
        t_max_N2 = np.log(lambda1 / lambda2) / (lambda1 - lambda2)
        N2_max = N0 * (lambda1 / (lambda2 - lambda1)) * (np.exp(-lambda1 * t_max_N2) - np.exp(-lambda2 * t_max_N2))
        print("РЕЖИМ: ПЕРЕХОДНЫЙ (λ₁ > λ₂)")
        print(f"Максимум N₂: t_max = {t_max_N2:.4f}, масса = {N2_max / N0:.2%} от N₀")
        print("N₂ накапливается быстрее, чем распадается до определенного момента")
        print("После пика — медленный распад N₂ с периодом T₂")

    print("=" * 60)


