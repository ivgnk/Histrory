# БЛОК 4: ИНТЕРАКТИВНЫЙ РЕЖИМ (для Jupyter Notebook)
# =============================================================================
# Здесь мы создаем ползунки, с помощью которых можно в реальном времени
# менять λ₁ и λ₂ и сразу видеть, как меняется форма кривой.
#
# FloatLogSlider - дает логарифмическую шкалу, чтобы можно было охватить
# диапазон от 0.001 до 100 (3 порядка).
# =============================================================================
def interactive_decay():
    """
    Запускает интерактивный виджет для исследования модели.
    Использует логарифмические ползунки для широкого диапазона параметров.

    Работает ТОЛЬКО в Jupyter Notebook / Jupyter Lab.
    Для обычного Python-скрипта нужно использовать plot_decay_chain() напрямую.
    """

    @interact(
        lambda1=FloatLogSlider(
            value=0.1, base=10, min=-3, max=2, step=0.1,
            description='λ₁ (скорость распада N₁)',
            style={'description_width': 'initial'}
        ),
        lambda2=FloatLogSlider(
            value=0.05, base=10, min=-3, max=2, step=0.1,
            description='λ₂ (скорость распада N₂)',
            style={'description_width': 'initial'}
        ),
        N0=fixed(100),  # Фиксируем начальную массу (можно изменить при желании)
        log_scale=FloatSlider(
            value=0, min=0, max=1, step=1,
            description='Логарифмическая шкала Y (0=Нет, 1=Да)',
            style={'description_width': 'initial'}
        )
    )
    def update(lambda1, lambda2, N0, log_scale):
        # Автоматический подбор t_max на основе самых медленных процессов
        # Берем 8 периодов полураспада самого медленного вещества
        min_lambda = min(lambda1, lambda2) if min(lambda1, lambda2) > 0 else 0.001
        t_max = 8 * np.log(2) / min_lambda
        plot_decay_chain(lambda1, lambda2, N0, t_max, bool(log_scale))

    return update


