# БЛОК 5: СРАВНИТЕЛЬНЫЙ АНАЛИЗ РЕЖИМОВ (СУТЬ РАЗЛИЧИЙ)
# =============================================================================
# Эта функция строит 4 графика, которые наглядно показывают,
# в чем принципиальная разница между переходным и вырожденным режимами,
# а не просто "толщина хвоста".
#
# Графики:
# 1. Сравнение формы N₂(t)
# 2. Логарифмический масштаб (вид хвоста)
# 3. Производная dN₂/dt (скорость изменения)
# 4. Отношение N₂/N₁ (степень "самостоятельности" дочернего вещества)
# =============================================================================
def compare_modes(lambda1_trans=0.2, lambda2_trans=0.05, lambda_degen=0.1, N0=100):
    """
    Сравнение переходного (λ₁ > λ₂) и вырожденного (λ₁ = λ₂) режимов.

    Параметры по умолчанию:
    - Переходный: λ₁=0.2, λ₂=0.05 (быстрое рождение, медленный распад)
    - Вырожденный: λ=0.1 (среднее значение, чтобы пик был примерно на том же месте)
    """

    # --- Рассчитываем оба режима ---
    t = np.linspace(0, 30, 1000)  # Фиксированное время для сравнения

    # Переходный режим (λ₁ > λ₂)
    l1, l2 = lambda1_trans, lambda2_trans
    t_trans, N1_trans, N2_trans, N3_trans = radioactive_decay_chain(l1, l2, N0, t_max=30, num_points=1000)

    # Вырожденный режим (λ₁ = λ₂ = lambda_degen)
    l = lambda_degen
    t_degen, N1_degen, N2_degen, N3_degen = radioactive_decay_chain(l, l, N0, t_max=30, num_points=1000)

    # --- Создаем 4 подграфика ---
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    ax1, ax2, ax3, ax4 = axes[0, 0], axes[0, 1], axes[1, 0], axes[1, 1]

    # --- График 1: Сравнение формы N₂(t) ---
    ax1.plot(t_trans, N2_trans, 'r-', linewidth=2.5,
             label=f'Переходный (λ₁={l1}, λ₂={l2})')
    ax1.plot(t_degen, N2_degen, 'b--', linewidth=2.5,
             label=f'Вырожденный (λ={l})')
    # Отмечаем максимумы
    t_max_trans = np.log(l1 / l2) / (l1 - l2) if l1 != l2 else 1 / l1
    t_max_degen = 1 / l
    ax1.axvline(t_max_trans, color='red', linestyle=':', alpha=0.5,
                label=f'Макс. переходный: t={t_max_trans:.2f}')
    ax1.axvline(t_max_degen, color='blue', linestyle=':', alpha=0.5,
                label=f'Макс. вырожденный: t={t_max_degen:.2f}')
    ax1.set_title('1. Сравнение формы кривой N₂(t)', fontsize=12)
    ax1.set_xlabel('Время')
    ax1.set_ylabel('Масса N₂')
    ax1.legend(loc='best')
    ax1.grid(True, alpha=0.3)

    # --- График 2: Логарифмический масштаб (вид хвоста) ---
    ax2.semilogy(t_trans, N2_trans, 'r-', linewidth=2.5, label='Переходный')
    ax2.semilogy(t_degen, N2_degen, 'b--', linewidth=2.5, label='Вырожденный')
    # Добавляем асимптоты для хвоста (чистые экспоненты)
    ax2.semilogy(t_trans, N0 * np.exp(-l2 * t_trans), 'r:', alpha=0.4,
                 label=f'Асимптота: e^(-{l2}·t)')
    ax2.semilogy(t_degen, N0 * np.exp(-l * t_degen), 'b:', alpha=0.4,
                 label=f'Асимптота: e^(-{l}·t)')
    ax2.set_title('2. Логарифмический масштаб: вид хвоста', fontsize=12)
    ax2.set_xlabel('Время')
    ax2.set_ylabel('log(Масса N₂)')
    ax2.legend(loc='best')
    ax2.grid(True, alpha=0.3, which='both')

    # --- График 3: Скорость изменения N₂ (производная) ---
    # Вычисляем производную численно (градиент)
    dN2_trans = np.gradient(N2_trans, t_trans)
    dN2_degen = np.gradient(N2_degen, t_degen)
    ax3.plot(t_trans, dN2_trans, 'r-', linewidth=2, label='Переходный')
    ax3.plot(t_degen, dN2_degen, 'b--', linewidth=2, label='Вырожденный')
    ax3.axhline(0, color='black', linestyle='-', alpha=0.3)  # Нулевая линия
    ax3.set_title('3. Скорость изменения N₂ (производная)', fontsize=12)
    ax3.set_xlabel('Время')
    ax3.set_ylabel('dN₂/dt')
    ax3.legend(loc='best')
    ax3.grid(True, alpha=0.3)

    # --- График 4: Отношение N₂/N₁ (степень "самостоятельности" N₂) ---
    ratio_trans = N2_trans / N1_trans
    ratio_degen = N2_degen / N1_degen
    ax4.plot(t_trans, ratio_trans, 'r-', linewidth=2, label='Переходный')
    ax4.plot(t_degen, ratio_degen, 'b--', linewidth=2, label='Вырожденный')
    # Горизонтальная линия - равновесное отношение для переходного режима
    ax4.axhline(l1 / l2, color='red', linestyle=':', alpha=0.5,
                label=f'Равновесие: λ₁/λ₂ = {l1 / l2:.2f}')
    ax4.set_title('4. Отношение N₂/N₁ (степень "самостоятельности" N₂)', fontsize=12)
    ax4.set_xlabel('Время')
    ax4.set_ylabel('N₂ / N₁')
    ax4.legend(loc='best')
    ax4.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.suptitle('СУТЬ РАЗЛИЧИЯ: Переходный vs Вырожденный режимы',
                 fontsize=14, y=1.02)
    plt.show()

    # --- Выводим текстовое пояснение (методологический вывод) ---
    print("\n" + "=" * 70)
    print("КЛЮЧЕВЫЕ РАЗЛИЧИЯ (НЕ В ТОЛЩИНЕ ХВОСТА):")
    print("=" * 70)
    print("1. Переходный (λ₁ > λ₂):")
    print("   → N₂ имеет два характерных времени — рост (определяется λ₁) и спад (λ₂).")
    print("   → Хвост определяется λ₂ (медленный распад самого N₂).")
    print("   → Отношение N₂/N₁ стремится к λ₁/λ₂ (вековое равновесие).")
    print("   → Можно извлечь ОБА параметра из разных участков кривой.")
    print("\n2. Вырожденный (λ₁ = λ₂):")
    print("   → N₂ имеет одно характерное время λ.")
    print("   → Хвост определяется λ, но с предэкспоненциальным множителем t.")
    print("   → Отношение N₂/N₁ = λ·t (линейно растет со временем до пика).")
    print("   → N₂ никогда не находится в равновесии с N₁ (кроме момента пика).")
    print("   → Из кривой можно извлечь ТОЛЬКО ОДИН параметр (λ).")
    print("\n3. МЕТОДОЛОГИЧЕСКИЙ ВЫВОД ДЛЯ ВАШЕЙ ЗАДАЧИ:")
    print("   → Переходный режим — это ХОРОШО ОБУСЛОВЛЕННАЯ задача.")
    print("   → Вырожденный случай — это НЕИДЕНТИФИЦИРУЕМОСТЬ модели.")
    print("   → В геофизике это означает, что разные комбинации параметров")
    print("     (плотность/скорость/сопротивление) могут давать одинаковый сигнал.")
    print("   → Решение: добавлять новые типы наблюдений (комплексирование)")
    print("     или использовать априорные геологические ограничения.")
    print("=" * 70)


