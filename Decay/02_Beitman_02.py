# БЛОК 2: ЯДРО МОДЕЛИ (Математика цепочки распадов)
# =============================================================================
# Здесь заложена вся физика. Функция возвращает массивы времени и масс
# для трех веществ: N1 (родитель), N2 (дочернее радиоактивное), N3 (стабильное).
#
# ВАЖНО: Именно здесь реализованы все три режима:
# - Обычный случай (λ₁ ≠ λ₂) с разностью экспонент
# - Вырожденный случай (λ₁ = λ₂) с формулой N₂ = N₀·λ·t·e^(-λt)
# - Закон сохранения массы для N₃ (N₃ = N₀ - N₁ - N₂)
# =============================================================================
def radioactive_decay_chain(lambda1, lambda2, N0=100, t_max=None, num_points=1000):
    """
    Модель последовательного радиоактивного распада:
    N1 -> N2 -> N3 (стабильный)

    Параметры:
    - lambda1: постоянная распада первого вещества (1/время)
    - lambda2: постоянная распада второго вещества (1/время)
    - N0: начальная масса первого вещества
    - t_max: максимальное время моделирования (если None, вычисляется автоматически)
    - num_points: количество точек по времени

    Возвращает:
    - t: массив времени
    - N1: масса первого вещества
    - N2: масса второго вещества
    - N3: масса стабильного продукта
    """

    # --- Автоматический подбор времени моделирования ---
    # Чтобы график всегда был информативным, мы вычисляем время,
    # за которое самое медленное вещество распадается на 99.3% (5 периодов)
    if t_max is None:
        # Находим минимальную скорость распада (самый медленный процесс)
        min_lambda = min(lambda1, lambda2) if min(lambda1, lambda2) > 0 else 0.001
        t_max = 5 * np.log(2) / min_lambda  # 5 периодов полураспада

    # Создаем равномерную сетку по времени
    t = np.linspace(0, t_max, num_points)

    # --- Аналитическое решение для N₁ (простая экспонента) ---
    N1 = N0 * np.exp(-lambda1 * t)

    # --- Аналитическое решение для N₂ (ключевая часть!) ---
    # Здесь мы разделяем два случая, чтобы избежать деления на ноль
    if abs(lambda1 - lambda2) < 1e-12:  # ВЫРОЖДЕННЫЙ СЛУЧАЙ (λ₁ = λ₂)
        # Формула: N₂(t) = N₀ · λ · t · e^(-λt)
        N2 = N0 * lambda1 * t * np.exp(-lambda1 * t)
    else:  # ОБЫЧНЫЙ СЛУЧАЙ (λ₁ ≠ λ₂)
        # Формула Бейтмана: N₂(t) = N₀ · (λ₁/(λ₂-λ₁)) · (e^(-λ₁t) - e^(-λ₂t))
        N2 = N0 * (lambda1 / (lambda2 - lambda1)) * (np.exp(-lambda1 * t) - np.exp(-lambda2 * t))

    # --- N₃ (стабильный продукт) из закона сохранения массы ---
    # Общая масса системы сохраняется: N₁ + N₂ + N₃ = N₀ = const
    N3 = N0 - N1 - N2
    # Защита от отрицательных значений (из-за ошибок округления на больших t)
    N3 = np.maximum(N3, 0)

    return t, N1, N2, N3


# =============================================================================
# БЛОК 3: БАЗОВАЯ ВИЗУАЛИЗАЦИЯ (Одиночный график)
# =============================================================================
# Эта функция строит "стандартный" график для заданных параметров.
# Она используется как основа для интерактивного режима и для демонстрации.
# =============================================================================
def plot_decay_chain(lambda1, lambda2, N0=100, t_max=None, log_scale=False, title_addon=""):
    """
    Строит два графика:
    - Слева: динамика масс N₁, N₂, N₃ во времени
    - Справа: информационная панель с ключевыми параметрами и режимом работы

    Параметры:
    - lambda1, lambda2: постоянные распада
    - N0: начальная масса
    - t_max: максимальное время (если None - авто)
    - log_scale: если True, то левый график в логарифмическом масштабе
    - title_addon: дополнительный текст в заголовок
    """

    # --- Шаг 1: Рассчитываем модель ---
    t, N1, N2, N3 = radioactive_decay_chain(lambda1, lambda2, N0, t_max)

    # --- Шаг 2: Создаем фигуру с двумя подграфиками ---
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    # --- Левый график: Динамика масс ---
    ax1.plot(t, N1, 'b-', linewidth=2.5, label=f'Вещество 1 (родитель)\nλ₁={lambda1:.2e}')
    ax1.plot(t, N2, 'r-', linewidth=2.5, label=f'Вещество 2 (дочернее)\nλ₂={lambda2:.2e}')
    ax1.plot(t, N3, 'g-', linewidth=2.5, label='Стабильный продукт (N₃)')
    # Закрашиваем область под кривой N₂ для наглядности
    ax1.fill_between(t, 0, N2, alpha=0.15, color='red')

    # Настройки осей
    ax1.set_xlabel('Время', fontsize=12)
    ax1.set_ylabel('Масса (в долях от N₀)', fontsize=12)
    ax1.set_title(f'Динамика масс в цепочке распада\n{title_addon}', fontsize=14)
    ax1.grid(True, alpha=0.3)
    ax1.legend(loc='best')

    # Логарифмическая шкала (если включена)
    if log_scale:
        ax1.set_yscale('log')
        ax1.set_ylim([1e-3, N0 * 1.1])

    # --- Правый график: Информационная панель ---
    # Вычисляем ключевые характеристики
    T1 = np.log(2) / lambda1 if lambda1 > 0 else np.inf
    T2 = np.log(2) / lambda2 if lambda2 > 0 else np.inf

    # Вычисляем положение максимума N₂
    if abs(lambda1 - lambda2) < 1e-12:
        # Вырожденный случай
        t_max_N2 = 1 / lambda1
        N2_max = N0 * lambda1 * t_max_N2 * np.exp(-1)
        regime = "ВЫРОЖДЕННЫЙ (λ₁ = λ₂)"
    else:
        # Общий случай
        t_max_N2 = np.log(lambda1 / lambda2) / (lambda1 - lambda2)
        if t_max_N2 > 0 and t_max_N2 < t[-1]:
            N2_max = N0 * (lambda1 / (lambda2 - lambda1)) * (np.exp(-lambda1 * t_max_N2) - np.exp(-lambda2 * t_max_N2))
            if lambda1 > lambda2:
                regime = "ПЕРЕХОДНЫЙ (λ₁ > λ₂)"
            else:
                regime = "ОБРАТНЫЙ ПЕРЕХОДНЫЙ (λ₁ < λ₂)"
        else:
            t_max_N2 = None
            N2_max = 0
            regime = "МОНОТОННОЕ НАКОПЛЕНИЕ (λ₁ >> λ₂)"

    # Собираем текст для панели
    info_text = f"""
    РЕЖИМ РАБОТЫ:
    ─────────────────────
    {regime}

    ПАРАМЕТРЫ:
    ─────────────────────
    λ₁ = {lambda1:.4e}
    λ₂ = {lambda2:.4e}
    T₁ (период N₁) = {T1:.3f}
    T₂ (период N₂) = {T2:.3f}
    Отношение λ₁/λ₂ = {lambda1 / lambda2:.3f}

    ХАРАКТЕРИСТИКИ N₂:
    ─────────────────────
    """

    if t_max_N2 is not None and t_max_N2 > 0:
        info_text += f"Максимум N₂:\n  t = {t_max_N2:.3f}\n  масса = {N2_max / N0:.1%} от N₀\n"
    else:
        info_text += "Ярко выраженного максимума нет\n"

    # Добавляем информацию о соотношении скоростей
    if lambda1 < lambda2:
        N2_eq = N0 * lambda1 / lambda2
        info_text += f"Вековое равновесие:\n  N₂ ≈ {N2_eq / N0:.1%} от N₀"
    elif lambda1 > lambda2:
        info_text += "Режим накопления:\n  N₂ накапливается быстрее,\n  чем распадается"
    else:
        info_text += "Симметричный режим:\n  λ₁ = λ₂"

    # Отображаем панель
    ax2.text(0.05, 0.95, info_text, transform=ax2.transAxes, fontsize=10,
             verticalalignment='top', bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.7),
             family='monospace')
    ax2.axis('off')  # Отключаем оси у правого графика

    plt.tight_layout()
    plt.show()

    return fig, (t, N1, N2, N3)


